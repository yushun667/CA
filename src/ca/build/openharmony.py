# Manifest / version parsing (pure)
# --------------------------------------------------------------------------- #


def parse_repo_manifest(xml_text: str) -> tuple[list[ManifestProject], list[str]]:
    """Parse ``.repo/manifests/*.xml`` into projects and ``<include>`` names."""

    try:
        root = ET.fromstring(xml_text)
    except ET.ParseError as exc:
        raise OpenHarmonyCorpusError(f"cannot parse repo manifest XML: {exc}") from exc
    projects: list[ManifestProject] = []
    includes: list[str] = []
    for element in root.iter():
        if element.tag == "project":
            name = (element.get("name") or "").strip()
            if not name:
                continue
            groups = tuple(
                group for group in (element.get("groups") or "").split(",") if group
            )
            projects.append(
                ManifestProject(
                    name=name,
                    path=(element.get("path") or name).strip(),
                    revision=(element.get("revision") or "").strip(),
                    groups=groups,
                )
            )
        elif element.tag == "include":
            name = (element.get("name") or "").strip()
            if name:
                includes.append(name)
    return projects, includes


def parse_assignments(text: str) -> dict[str, str]:
    """Parse simple GN-style ``key = "value"`` assignments (version files)."""

    values: dict[str, str] = {}
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        key, _, raw_value = stripped.partition("=")
        value = raw_value.strip().rstrip(";").strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        if key.strip():
            values[key.strip()] = value
    return values


def project_distribution(projects: Iterable[ManifestProject]) -> dict[str, int]:
    """Count manifest projects by their first two path components."""

    counts: dict[str, int] = {}
    for project in projects:
        parts = Path(project.path).parts
        key = "/".join(parts[:2]) if len(parts) >= 2 else (parts[0] if parts else project.name)
        counts[key] = counts.get(key, 0) + 1
    return dict(sorted(counts.items()))



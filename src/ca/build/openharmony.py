# Compile database filtering / reporting (pure)
# --------------------------------------------------------------------------- #


def _entry_paths(entry: Mapping[str, Any]) -> tuple[Path | None, Path | None]:
    """Return (absolute file, absolute directory) for a compdb entry."""

    raw_file = entry.get("file")
    raw_directory = entry.get("directory")
    if not isinstance(raw_file, str) or not raw_file.strip():
        return None, None
    directory = Path(raw_directory) if isinstance(raw_directory, str) and raw_directory else None
    file_path = Path(raw_file)
    if not file_path.is_absolute():
        file_path = (directory or Path(".")) / file_path
    return Path(os.path.normpath(os.path.abspath(file_path))), (
        Path(os.path.normpath(os.path.abspath(directory))) if directory is not None else None
    )


def filter_compilation_database(entries: Any) -> CompdbFilterResult:
    """Keep only C/C++ translation units from raw Ninja/GN compdb entries."""

    if not isinstance(entries, list):
        raise OpenHarmonyCorpusError("compilation database must be a JSON array")
    result = CompdbFilterResult(raw_count=len(entries))
    seen: set[str] = set()

    def drop(reason: str) -> None:
        result.filtered[reason] = result.filtered.get(reason, 0) + 1

    for entry in entries:
        if not isinstance(entry, Mapping):
            drop("entry-not-an-object")
            continue
        file_path, _ = _entry_paths(entry)
        if file_path is None:
            drop("missing-file")
            continue
        language = language_for_path(file_path)
        if language is None:
            suffix = file_path.suffix or "<none>"
            drop(f"unsupported-language:{suffix}")
            continue
        has_command = isinstance(entry.get("command"), str) and bool(
            entry["command"].strip()
        )
        has_arguments = isinstance(entry.get("arguments"), (list, tuple)) and bool(
            entry["arguments"]
        )
        if not (has_command or has_arguments):
            drop("missing-command")
            continue
        directory = entry.get("directory")
        key = f"{file_path}\x00{directory}\x00{entry.get('command') or entry.get('arguments')}"
        if key in seen:
            drop("duplicate")
            continue
        seen.add(key)
        normalized = dict(entry)
        normalized["file"] = str(file_path)
        result.kept.append(normalized)
    return result


def directory_distribution(
    entries: Sequence[Mapping[str, Any]],
    source_root: str | os.PathLike[str],
    *,
    depth: int = 2,
) -> dict[str, int]:
    """Count TUs per top-level source directory (``base``, ``foundation``...)."""

    root = Path(source_root).resolve()
    counts: dict[str, int] = {}
    for entry in entries:
        file_path, _ = _entry_paths(entry)
        if file_path is None:
            continue
        try:
            relative = file_path.resolve().relative_to(root)
        except (OSError, ValueError):
            counts["<outside-source-root>"] = counts.get("<outside-source-root>", 0) + 1
            continue
        parts = relative.parts
        key = "/".join(parts[:depth]) if len(parts) >= depth else (parts[0] if parts else ".")
        counts[key] = counts.get(key, 0) + 1
    return dict(sorted(counts.items()))


#: Marker substrings used to prefer device (arm64) variants over host ones.
_ARM64_MARKERS = (
    "--target=aarch64-linux-ohos",
    "--target=aarch64-linux-gnu",
    "-march=armv8",
)
_HOST_MARKERS = (
    "--target=x86_64-linux-gnu",
    "--target=x86_64-unknown-linux-gnu",
    "-m64",
)
_TEST_SEGMENTS = frozenset(
    {"test", "tests", "unittest", "unittests", "fuzztest", "xts", "ostest", "testfwk"}
)
_GENERATED_TOP_DIRS = frozenset({"out", "prebuilts"})


@dataclass
class UniqueSelection:
    """One representative command per unique source file."""

    entries: list[dict[str, Any]] = field(default_factory=list)
    stats: dict[str, Any] = field(default_factory=dict)


def _variant_score(
    entry: Mapping[str, Any], relative_parts: Sequence[str]
) -> tuple[int, int, int, int, str]:
    """Sort key: prefer arm64 device, non-test, non-host, short, deterministic."""

    command = entry.get("command") or ""
    is_arm64 = int(any(marker in command for marker in _ARM64_MARKERS))
    is_test = int(any(part in _TEST_SEGMENTS for part in relative_parts))
    is_host = int(
        not is_arm64 and any(marker in command for marker in _HOST_MARKERS)
    )
    return (is_arm64, -is_test, -is_host, -len(command), command)


def select_unique_commands(
    entries: Iterable[Mapping[str, Any]],
    *,
    source_root: str | os.PathLike[str] | None = None,
    drop_top_dirs: Sequence[str] = ("out", "prebuilts"),
) -> UniqueSelection:
    """Collapse multi-variant commands to one representative command per file.

    Priority: device (arm64) target > non-test path > non-host target > shortest
    command > deterministic command string. ``out/``/``prebuilts/`` generated or
    toolchain entries are dropped when ``source_root`` is provided. Every kept
    entry records ``variants_total``/``variants_dropped`` so provenance stays
    auditable.
    """

    root = Path(source_root).resolve() if source_root is not None else None
    dropped_dirs = frozenset(drop_top_dirs)
    best: dict[str, tuple[tuple[int, int, int, int, str], Mapping[str, Any]]] = {}
    counts: dict[str, int] = {}
    dropped_generated = 0
    for entry in entries:
        if not isinstance(entry, Mapping):
            continue
        raw_file = entry.get("file")
        if not isinstance(raw_file, str) or not raw_file:
            continue
        file_path = Path(raw_file)
        if not file_path.is_absolute():
            directory = entry.get("directory")
            if isinstance(directory, str) and directory:
                file_path = Path(directory) / file_path
        file_path = Path(os.path.normpath(os.path.abspath(file_path)))
        key = str(file_path)
        relative_parts: tuple[str, ...] = ()
        if root is not None:
            try:
                relative_parts = file_path.relative_to(root).parts
            except ValueError:
                relative_parts = file_path.parts
            if relative_parts and relative_parts[0] in dropped_dirs:
                dropped_generated += 1
                continue
        score = _variant_score(entry, relative_parts)
        counts[key] = counts.get(key, 0) + 1
        current = best.get(key)
        if current is None or score > current[0]:
            best[key] = (score, entry)

    by_top: dict[str, int] = {}
    selected: list[dict[str, Any]] = []
    for key in sorted(best):
        _, entry = best[key]
        total = counts[key]
        chosen = dict(entry)
        chosen["file"] = key
        chosen["variants_total"] = total
        chosen["variants_dropped"] = total - 1
        selected.append(chosen)
        top = "."
        if root is not None:
            try:
                parts = Path(key).relative_to(root).parts
                top = parts[0] if parts else "."
            except ValueError:
                top = Path(key).parts[0] if Path(key).parts else "."
        by_top[top] = by_top.get(top, 0) + 1

    files_with_variants = sum(1 for count in counts.values() if count > 1)
    dropped_variants = sum(count - 1 for count in counts.values())
    stats = {
        "tu_count": len(selected),
        "unique_files": len(best),
        "files_with_variants": files_with_variants,
        "dropped_variants": dropped_variants,
        "dropped_generated_entries": dropped_generated,
        "by_top1": dict(sorted(by_top.items(), key=lambda item: -item[1])),
    }
    return UniqueSelection(entries=selected, stats=stats)


#: Shard plan for the unique-file acceptance index (path-prefix based).
OH_SHARD_PREFIXES: dict[str, tuple[str, ...]] = {
    "S1": ("foundation/bundlemanager", "foundation/ability"),
    "S2": (
        "foundation/arkui",
        "foundation/graphic",
        "foundation/window",
        "foundation/multimedia",
        "foundation/multimodalinput",
    ),
    "S3": ("foundation/",),
    "S4": ("base/",),
    "S5": ("third_party/",),
    "S6": ("arkcompiler/",),
    "S7": ("drivers/", "kernel/", "device/"),
    "S8": (
        "developtools/",
        "commonlibrary/",
        "test/",
        "domains/",
        "applications/",
        "build/",
        "vendor/",
    ),
}


def shard_for_path(path: str | os.PathLike[str], source_root: str | os.PathLike[str]) -> str:
    """Return the SHARD id (S1..S8) for a source path inside ``source_root``."""

    file_path = Path(os.path.abspath(path))
    root = Path(source_root).resolve()
    try:
        relative = file_path.relative_to(root).as_posix()
    except ValueError:
        relative = file_path.as_posix()
    for shard, prefixes in OH_SHARD_PREFIXES.items():
        if relative.startswith(prefixes):
            return shard
    return "S8"


def shard_plan(
    entries: Iterable[Mapping[str, Any]],
    source_root: str | os.PathLike[str],
) -> tuple[dict[str, list[dict[str, Any]]], dict[str, int]]:
    """Split compdb entries into the acceptance shards; returns (entries, counts)."""

    shards: dict[str, list[dict[str, Any]]] = {shard: [] for shard in OH_SHARD_PREFIXES}
    for entry in entries:
        if not isinstance(entry, Mapping):
            continue
        raw_file = entry.get("file")
        if not isinstance(raw_file, str) or not raw_file:
            continue
        file_path = Path(raw_file)
        if not file_path.is_absolute():
            directory = entry.get("directory")
            if isinstance(directory, str) and directory:
                file_path = Path(directory) / file_path
        shard = shard_for_path(str(file_path), source_root)
        shards.setdefault(shard, []).append(dict(entry))
    counts = {shard: len(items) for shard, items in sorted(shards.items())}
    return shards, counts


def write_unique_compdb(
    selection: UniqueSelection,
    path: str | os.PathLike[str],
) -> Path:
    """Write a unique-file compilation database atomically."""

    return write_compilation_database(selection.entries, path)


def summarize_compdb(entries: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    """Language distribution and per-suffix counts over kept entries."""

    languages: dict[str, int] = {}
    suffixes: dict[str, int] = {}
    for entry in entries:
        file_path, _ = _entry_paths(entry)
        if file_path is None:
            continue
        language = language_for_path(file_path) or "unknown"
        languages[language] = languages.get(language, 0) + 1
        suffix = file_path.suffix or "<none>"
        suffixes[suffix] = suffixes.get(suffix, 0) + 1
    return {
        "tu_count": len(entries),
        "languages": dict(sorted(languages.items())),
        "suffixes": dict(sorted(suffixes.items())),
    }



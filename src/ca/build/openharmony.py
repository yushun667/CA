"""OpenHarmony compile-database corpus helpers (real C/C++ translation units).

OpenHarmony 6.1 is a ~500-project ``repo`` checkout whose build is generated by
GN and executed by Ninja. We do **not** need (or want) a full compile to get a
real compilation database: the GN phase writes ``out/<board>/build.ninja`` and
Ninja can dump every compile rule as JSON:

    prebuilts/build-tools/linux-x86/bin/ninja -C out/rk3588 -t compdb

(or ``gn gen --export-compile-commands``). The entries carry the real
toolchain flags (clang target triple, sysroot, ``-D`` defines, include paths)
exactly as Ninja would execute them.

This module keeps the portable parts (``repo`` manifest parsing, compdb
filtering to C/C++, directory distribution, metadata, command construction)
pure so they are unit tested without the server, the 13 GB checkout or Docker.
Server-specific steps live in :func:`build_openharmony_corpus` and are driven
from the task report; they never touch the read-only original tree.
"""

from __future__ import annotations

import json
import os
import subprocess
import tempfile
import xml.etree.ElementTree as ET
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Iterable, Mapping, Sequence

from ca.build.compdb import language_for_path

SOURCE_OPENHARMONY = "compile_commands"
DEFAULT_PRODUCT = "opi5plus"
DEFAULT_BOARD = "rk3588"
DEFAULT_OS_LEVEL = "standard"
DEFAULT_ARCH = "arm64"


class OpenHarmonyCorpusError(RuntimeError):
    """OpenHarmony checkout/compdb generation failed."""


@dataclass(frozen=True)
class OpenHarmonyTarget:
    """Product/board identity used for ``out/<board>`` and metadata."""

    product: str = DEFAULT_PRODUCT
    board: str = DEFAULT_BOARD
    os_level: str = DEFAULT_OS_LEVEL
    arch: str = DEFAULT_ARCH

    @property
    def out_name(self) -> str:
        return self.board

    def out_dir(self, source_root: str | os.PathLike[str]) -> Path:
        return Path(source_root) / "out" / self.out_name


@dataclass(frozen=True)
class ManifestProject:
    """One ``<project>`` element from a ``repo`` manifest."""

    name: str
    path: str
    revision: str = ""
    groups: tuple[str, ...] = ()


@dataclass
class CompdbFilterResult:
    """Outcome of filtering a raw Ninja/GN compile database."""

    kept: list[dict[str, Any]] = field(default_factory=list)
    filtered: dict[str, int] = field(default_factory=dict)
    raw_count: int = 0

    @property
    def tu_count(self) -> int:
        return len(self.kept)

    @property
    def filtered_count(self) -> int:
        return sum(self.filtered.values())

    def summary(self) -> dict[str, Any]:
        return {
            "raw_entries": self.raw_count,
            "tu_count": self.tu_count,
            "filtered_entries": self.filtered_count,
            "filtered_reasons": dict(sorted(self.filtered.items())),
        }



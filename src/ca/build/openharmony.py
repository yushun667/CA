def prebuilt_tool(source_root: str | os.PathLike[str], name: str) -> Path:
    return (
        Path(source_root) / "prebuilts" / "build-tools" / "linux-x86" / "bin" / name
    )


def ninja_compdb_command(
    ninja: str | os.PathLike[str],
    out_dir: str | os.PathLike[str],
) -> list[str]:
    return [os.fspath(ninja), "-C", os.fspath(out_dir), "-t", "compdb"]


def gn_gen_command(
    gn: str | os.PathLike[str],
    out_dir: str | os.PathLike[str],
    *,
    gn_args: str = "",
    export_compile_commands: bool = True,
) -> list[str]:
    command = [os.fspath(gn), "gen", os.fspath(out_dir)]
    if gn_args:
        command.append(f"--args={gn_args}")
    if export_compile_commands:
        command.append("--export-compile-commands")
    return command


def docker_command(
    image: str,
    source_root: str | os.PathLike[str],
    command: Sequence[str],
    *,
    docker: str = "docker",
) -> list[str]:
    root = os.path.abspath(source_root)
    return [
        docker,
        "run",
        "--rm",
        "-v",
        f"{root}:{root}",
        "-w",
        root,
        image,
        *command,
    ]



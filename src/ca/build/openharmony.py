def write_compilation_database(
    entries: Iterable[Mapping[str, Any]],
    path: str | os.PathLike[str],
) -> Path:
    """Atomically write filtered standard cdbb entries."""

    destination = Path(path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    payload = json.dumps(list(entries), indent=2, ensure_ascii=False) + "\n"
    fd, temporary = tempfile.mkstemp(
        prefix=".compile_commands-", suffix=".json", dir=str(destination.parent)
    )
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(payload)
        os.replace(temporary, destination)
    except BaseException:
        Path(temporary).unlink(missing_ok=True)
        raise
    return destination.resolve()


def write_metadata(metadata: Mapping[str, Any], path: str | os.PathLike[str]) -> Path:
    destination = Path(path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(
        prefix=".metadata-", suffix=".json", dir=str(destination.parent)
    )
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            json.dump(dict(metadata), handle, indent=2, ensure_ascii=False)
            handle.write("\n")
        os.replace(temporary, destination)
    except BaseException:
        Path(temporary).unlink(missing_ok=True)
        raise
    return destination.resolve()


def build_metadata(
    *,
    target: OpenHarmonyTarget,
    source_root: str | os.PathLike[str],
    raw_count: int,
    entries: Sequence[Mapping[str, Any]],
    filtered: Mapping[str, int],
    version: str,
    manifest_commit: str,
    tools: Mapping[str, str],
    commands: Mapping[str, str],
    timings: Mapping[str, float],
    extra: Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    """Assemble the ``metadata.json`` record for the corpus."""

    metadata: dict[str, Any] = {
        "ecosystem": "openharmony",
        "product": target.product,
        "board": target.board,
        "os_level": target.os_level,
        "arch": target.arch,
        "source_root": str(Path(source_root).resolve()),
        "out_dir": str(target.out_dir(source_root).resolve()),
        "version": version,
        "manifest_commit": manifest_commit,
        "tools": dict(sorted(tools.items())),
        "compdb": {
            "raw_entries": raw_count,
            "tu_count": len(entries),
            "filtered_entries": sum(filtered.values()),
            "filtered_reasons": dict(sorted(filtered.items())),
            **summarize_compdb(entries),
        },
        "directory_distribution": directory_distribution(entries, source_root),
        "commands": dict(commands),
        "timings_seconds": {key: round(value, 2) for key, value in timings.items()},
    }
    if extra:
        metadata.update(extra)
    return metadata


def tool_versions(source_root: str | os.PathLike[str]) -> dict[str, str]:
    """Return versions/availability of the prebuilt GN/Ninja/clang tools."""

    versions: dict[str, str] = {}
    gn = prebuilt_tool(source_root, "gn")
    ninja = prebuilt_tool(source_root, "ninja")
    versions["gn_exists"] = str(gn.is_file())
    versions["ninja_exists"] = str(ninja.is_file())
    versions["gn"] = _first_line([os.fspath(gn), "--version"]) if gn.is_file() else ""
    versions["ninja"] = _first_line([os.fspath(ninja), "--version"]) if ninja.is_file() else ""
    return versions


def _first_line(argv: Sequence[str]) -> str:
    try:
        completed = subprocess.run(list(argv), capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.TimeoutExpired):
        return ""
    if completed.returncode != 0:
        return ""
    text = (completed.stdout or completed.stderr or "").strip()
    return text.splitlines()[0] if text else ""



def _resolve_output(output: str | os.PathLike[str], repo_root: str) -> Path:
    path = Path(output)
    if not path.is_absolute():
        path = Path(repo_root) / path
    if path.is_dir() or str(output).endswith(os.sep):
        path = path / "compile_commands.json"
    return Path(os.path.abspath(path))


def capture_build(
    command: str | Sequence[str],
    output: str | os.PathLike[str],
    repo_root: str | os.PathLike[str],
    jobs: int = 1,
) -> list[CompilationUnit]:
    """Run ``command`` with compiler wrappers and write a compile database.

    ``command`` is a shell string (run via ``/bin/sh -c``) or an argv sequence.
    It runs with the captured repository as working directory. ``output`` is the
    ``compile_commands.json`` path (an existing directory means
    ``<dir>/compile_commands.json``). ``jobs`` is informational: parallelism is
    owned by the build command; it is forwarded as ``CA_CAPTURE_JOBS`` only.

    Returns the captured units and writes the database. Raises
    :class:`BuildCaptureError` when the build exits nonzero (after keeping the
    partial database) or :class:`ValueError` when no C/C++ TU was captured.
    """

    if isinstance(jobs, bool) or not isinstance(jobs, int) or jobs < 1:
        raise ValueError(f"jobs must be a positive integer, got {jobs!r}")
    root = normalize_repo_root(repo_root)
    output_path = _resolve_output(output, root)
    is_shell = isinstance(command, str)
    argv: str | list[str] = command if is_shell else [str(token) for token in command]

    with CaptureSession(root) as session:
        completed = subprocess.run(
            argv,
            shell=is_shell,
            cwd=root,
            env=session.child_env({"CA_CAPTURE_JOBS": str(jobs)}),
        )
        units = session.collect()
        session.write_compdb(output_path, units)

    if completed.returncode != 0:
        raise BuildCaptureError(
            "build command exited with code "
            f"{completed.returncode} after capturing {len(units)} C/C++ "
            f"translation unit(s); partial database kept at {output_path}",
            returncode=completed.returncode,
            output=str(output_path),
            captured=len(units),
        )
    if not units:
        raise ValueError(
            "captured no C/C++ translation units: the build did not invoke a "
            "wrapped compiler, or all invocations were linker/probe steps "
            f"(captured {session.recorded_invocations} invocation records)"
        )
    return units



"""Capture the real compiler invocations of a build with wrapper scripts.

``capture_build`` installs tiny ``cc``/``c++``/``gcc``/``clang`` shims in a
temporary directory, prepends it to ``PATH`` and runs the user build command.
Each shim resolves the *real* compiler (absolute path baked in at install time
or overridden via ``CA_REAL_CC``/``CA_REAL_CXX``/``CA_REAL_<NAME>``), appends a
JSON record (cwd + complete argv) to the capture directory, and then executes
the real compiler unchanged.

Concurrency safety: every invocation writes its own ``rec-*.json`` file via
``tempfile.mkstemp`` (independent-file scheme, no shared append races), and the
records are merged only after the build finishes. The captured database is
deterministic (deduplicated, sorted) so a repeated build is idempotent.

Only invocations that name a C/C++ source file become compilation units; linker
steps, ``.S`` assembly compiles and compiler capability probes are recorded
but filtered out and counted. When the build fails, already captured units are
still written to ``compile_commands.json`` before :class:`BuildCaptureError`
reports the exit code.
"""

from __future__ import annotations

import json
import os
import re
import shlex
import shutil
import subprocess
import sys
import tempfile
import textwrap
from pathlib import Path
from typing import Any, Mapping, Sequence

from ca.build.compdb import (
    language_for_path,
    normalize_repo_root,
    write_compilation_database,
)
from ca.core.ids import tu_id
from ca.core.schema import CompilationUnit

SOURCE_CAPTURE = "capture"

DEFAULT_WRAPPER_NAMES = ("cc", "c++", "gcc", "g++", "clang", "clang++")

_CC_NAMES = frozenset({"cc", "gcc", "clang"})
_CXX_NAMES = frozenset({"c++", "g++", "clang++"})

_WRAPPER_TEMPLATE = """#!/bin/sh
# Generated by ca.build.capture: record this compiler invocation, run it.
set -u
real=""
{override}
if [ -z "$real" ]; then
    real={baked}
fi
if [ -z "$real" ]; then
    printf '%s\\n' "ca-capture: could not resolve real compiler for {name}" >&2
    exit 127
fi
if [ -n "${{CA_CAPTURE_RECORDER:-}}" ]; then
    if ! "${{CA_CAPTURE_PYTHON:-python3}}" "$CA_CAPTURE_RECORDER" "$real"{injected} "$@"; then
        printf '%s\\n' "ca-capture: warning: failed to record {name} invocation" >&2
    fi
fi
exec "$real"{injected} "$@"
"""

_RECORDER_SOURCE = '''"""Record one compiler invocation for ca.build.capture (run by wrappers)."""

import json
import os
import sys
import tempfile


def main() -> int:
    capture_dir = os.environ.get("CA_CAPTURE_DIR", "")
    if not capture_dir or len(sys.argv) < 2:
        return 0
    record = {
        "cwd": os.getcwd(),
        "driver": sys.argv[1],
        "arguments": sys.argv[2:],
        "pid": os.getpid(),
    }
    try:
        fd, path = tempfile.mkstemp(dir=capture_dir, prefix="rec-", suffix=".json")
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            json.dump(record, handle, ensure_ascii=False)
    except OSError:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
'''


class BuildCaptureError(RuntimeError):
    """The captured build exited nonzero; partial results were kept on disk."""

    def __init__(
        self,
        message: str,
        *,
        returncode: int,
        output: str = "",
        captured: int = 0,
    ) -> None:
        super().__init__(message)
        self.returncode = returncode
        self.output = output
        self.captured = captured


def _sanitize_env_suffix(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9]", "_", name).upper()


def _wrapper_kind(name: str) -> str:
    if name in _CC_NAMES:
        return "cc"
    if name in _CXX_NAMES:
        return "cxx"
    return "other"


def _resolve_executable(name: str) -> str | None:
    found = shutil.which(name)
    if not found:
        return None
    return os.path.abspath(found)


def _find_c_source(arguments: Sequence[str]) -> str | None:
    """Last non-option argument that looks like a C/C++ source file."""

    for token in reversed(arguments):
        if not token or token.startswith("-"):
            continue
        if language_for_path(token) is not None:
            return token
    return None


class CaptureSession:
    """Temporary wrapper directory + JSON records for one captured build.

    Public usage::

        with CaptureSession(repo_root) as session:
            subprocess.run(["make", "-j8"], cwd=repo_root, env=session.child_env())
            units = session.collect()
            session.write_compdb(output, units)

    ``compilers`` maps wrapper name -> real compiler. ``None`` resolves the
    wrapper name from the parent ``PATH``; names that cannot be resolved are
    skipped unless explicitly requested. ``extra_wrappers`` adds passthrough
    names (e.g. a cross compiler such as ``riscv-none-elf-gcc``).
    ``extra_args`` injects fixed arguments into a wrapper: they are recorded in
    the captured argv *and* passed to the real tool, so a driver-default fix
    such as ``-mabi=lp64d`` stays visible and truthful in the database.
    """

    def __init__(
        self,
        repo_root: str | os.PathLike[str],
        *,
        compilers: Mapping[str, str | os.PathLike[str] | None] | None = None,
        extra_wrappers: Sequence[str] = (),
        extra_args: Mapping[str, Sequence[str]] | None = None,
    ) -> None:
        self.repo_root = normalize_repo_root(repo_root)
        if not os.path.isdir(self.repo_root):
            raise FileNotFoundError(f"repo_root is not a directory: {self.repo_root}")
        self._work_dir = Path(
            tempfile.mkdtemp(
                prefix="capture-",
                dir=self._ensure_work_root(),
            )
        )
        self.bin_dir = self._work_dir / "bin"
        self.capture_dir = self._work_dir / "records"
        self.bin_dir.mkdir()
        self.capture_dir.mkdir()
        self.recorder = self._work_dir / "record.py"
        self.recorder.write_text(_RECORDER_SOURCE, encoding="utf-8")
        self.compilers: dict[str, str] = {}
        self.compiler_arguments: dict[str, tuple[str, ...]] = {
            str(name): tuple(str(argument) for argument in arguments)
            for name, arguments in (extra_args or {}).items()
        }
        self.recorded_invocations = 0
        self.skipped_invocations = 0
        try:
            self._install(compilers, extra_wrappers)
        except BaseException:
            self.cleanup()
            raise

    # -- setup -------------------------------------------------------------

    def _ensure_work_root(self) -> str:
        root = Path(self.repo_root) / ".tmp" / "agent-build"
        try:
            root.mkdir(parents=True, exist_ok=True)
        except OSError:
            root = Path(tempfile.gettempdir()) / "ca-capture"
            root.mkdir(parents=True, exist_ok=True)
        return str(root)

    def _install(
        self,
        compilers: Mapping[str, str | os.PathLike[str] | None] | None,
        extra_wrappers: Sequence[str],
    ) -> None:
        if compilers is None:
            requested: list[tuple[str, str | os.PathLike[str] | None, bool]] = [
                (name, None, False) for name in DEFAULT_WRAPPER_NAMES
            ]
        else:
            requested = [(name, real, True) for name, real in compilers.items()]
        for name in extra_wrappers:
            requested.append((name, None, True))

        seen: set[str] = set()
        for name, real, required in requested:
            if not name or name in seen:
                continue
            seen.add(name)
            if real is None:
                resolved = _resolve_executable(name)
                if resolved is None:
                    if required:
                        raise FileNotFoundError(
                            f"cannot resolve compiler {name!r} on PATH for capture"
                        )
                    continue
            else:
                resolved = os.path.abspath(os.fspath(real))
                if not (os.path.isfile(resolved) and os.access(resolved, os.X_OK)):
                    raise FileNotFoundError(f"compiler {name!r} is not executable: {resolved}")
            self._write_wrapper(name, resolved)
            self.compilers[name] = resolved

        if not self.compilers:
            raise RuntimeError(
                "capture installed no compiler wrappers; none of "
                f"{', '.join(DEFAULT_WRAPPER_NAMES)} were found on PATH"
            )

    def _write_wrapper(self, name: str, real: str) -> None:
        kind = _wrapper_kind(name)
        if kind == "cc":
            override = 'real="${CA_REAL_CC:-}"'
        elif kind == "cxx":
            override = 'real="${CA_REAL_CXX:-}"'
        else:
            override = f'real="${{CA_REAL_{_sanitize_env_suffix(name)}:-}}"'
        injected = "".join(
            " " + shlex.quote(argument)
            for argument in self.compiler_arguments.get(name, ())
        )
        script = _WRAPPER_TEMPLATE.format(
            name=name,
            override=override,
            baked=shlex.quote(real),
            injected=injected,
        )
        destination = self.bin_dir / name
        destination.write_text(script, encoding="utf-8")
        destination.chmod(0o755)

    # -- environment / cleanup --------------------------------------------

    @property
    def env(self) -> dict[str, str]:
        """Environment additions that make the wrappers visible and working."""

        inherited_path = os.environ.get("PATH", "")
        path = str(self.bin_dir)
        if inherited_path:
            path = path + os.pathsep + inherited_path
        return {
            "PATH": path,
            "CA_CAPTURE_DIR": str(self.capture_dir),
            "CA_CAPTURE_RECORDER": str(self.recorder),
            "CA_CAPTURE_PYTHON": sys.executable or "python3",
            "CA_WRAPPER_DIR": str(self.bin_dir),
        }

    def child_env(self, extra: Mapping[str, str] | None = None) -> dict[str, str]:
        environment = dict(os.environ)
        environment.update(self.env)
        if extra:
            environment.update({str(key): str(value) for key, value in extra.items()})
        return environment

    def cleanup(self) -> None:
        shutil.rmtree(self._work_dir, ignore_errors=True)

    def __enter__(self) -> CaptureSession:
        return self

    def __exit__(self, *exc_info: object) -> None:
        self.cleanup()

    # -- results -----------------------------------------------------------

    def _load_records(self) -> list[dict[str, Any]]:
        records: list[dict[str, Any]] = []
        for path in sorted(self.capture_dir.glob("rec-*.json")):
            try:
                data = json.loads(path.read_text(encoding="utf-8"))
            except (OSError, json.JSONDecodeError):
                continue
            if isinstance(data, dict):
                records.append(data)
        return records

    def collect(self) -> list[CompilationUnit]:
        """Merge records into deterministic compilation units."""

        records = self._load_records()
        self.recorded_invocations = len(records)
        units: list[CompilationUnit] = []
        seen: set[str] = set()
        skipped = 0
        root = self.repo_root
        for record in records:
            cwd = record.get("cwd")
            driver = record.get("driver")
            arguments = record.get("arguments")
            if not isinstance(cwd, str) or not isinstance(driver, str):
                skipped += 1
                continue
            if not isinstance(arguments, list) or not all(
                isinstance(token, str) for token in arguments
            ):
                skipped += 1
                continue
            source = _find_c_source(arguments)
            if source is None:
                skipped += 1
                continue
            directory = os.path.normpath(os.path.abspath(cwd))
            source_path = Path(source)
            if not source_path.is_absolute():
                source_path = Path(directory) / source_path
            source_path = Path(os.path.normpath(os.path.abspath(source_path)))
            language = language_for_path(source_path)
            if language is None:
                skipped += 1
                continue
            argv = tuple(arguments)
            unit = CompilationUnit(
                id=tu_id(str(source_path), directory, argv),
                file=str(source_path),
                directory=directory,
                repo_root=root,
                arguments=argv,
                language=language,
                source=SOURCE_CAPTURE,
                driver=driver,
            )
            if unit.id in seen:
                continue
            seen.add(unit.id)
            units.append(unit)
        self.skipped_invocations = skipped
        units.sort(key=lambda unit: (unit.file, unit.arguments))
        return units

    def write_compdb(
        self,
        path: str | os.PathLike[str],
        units: Sequence[CompilationUnit] | None = None,
    ) -> Path:
        if units is None:
            units = self.collect()
        return write_compilation_database(units, path)



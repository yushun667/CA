/**
 * AI explanation panel for the CA DSH plugin (Client half).
 *
 * `createExplainPanel(React, bag)` returns a component with props
 * `{symbol, language?, onNavigate?}`. The component is self-contained: it owns
 * the "Explain with AI" button, an optional question field, loading / error /
 * retry states, a safe Markdown rendering of the model answer, a copy button and
 * the evidence-count / model footer. It renders inline styles only (no global
 * CSS injection) and never touches the host DOM outside its own subtree.
 *
 * Data flow: the explanation itself is produced by the Host `explain` service
 * (native DSH model capability) and reaches this component through the
 * authenticated RPC endpoint `explain` on channel `/dsh-ca`. The CA backend is
 * read-only here: this module never calls the CA HTTP API directly.
 *
 * Safety: model output is parsed into plain data by `./markdown.js` and rendered
 * with React elements, so every model-authored character is escaped by React.
 * No raw HTML injection is used anywhere in this module.
 */


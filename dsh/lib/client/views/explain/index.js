/**
 * Normalize any language tag to one of the supported explain languages.
 * @param {unknown} value
 * @returns {'en'|'zh'}
 */
export function normalizeLanguage(value) {
  return typeof value === 'string' && /^zh/i.test(value.trim()) ? 'zh' : DEFAULT_LANGUAGE
}

/** Small client-side error carrying a stable code (never a server stack). */
function clientError(code, message) {
  const error = new Error(String(message || 'Explanation request failed'))
  error.name = 'ExplainClientError'
  error.code = typeof code === 'string' && code.length > 0 ? code : 'EXPLAIN_CLIENT_ERROR'
  return error
}

/** True when an error means the caller intentionally cancelled the request. */
function isAbortError(error) {
  if (!error || typeof error !== 'object') return false
  if (error.name === 'AbortError') return true
  return (
    error.code === 'EXPLAIN_ABORTED' ||
    error.code === 'ABORTED' ||
    error.code === 'CANCELLED' ||
    error.code === 'ABORT_ERR'
  )
}

/**
 * Build the RPC payload sent to the Host `explain` endpoint.
 *
 * @param {{symbol?: unknown, language?: unknown, question?: unknown}} input
 * @returns {{symbol: string, language: 'en'|'zh', question?: string}}
 */
export function buildExplainRequest(input) {
  const rawSymbol = input && typeof input.symbol === 'string' ? input.symbol.trim() : ''
  if (rawSymbol.length === 0) {
    throw clientError('EXPLAIN_INVALID_ARGUMENT', 'A function symbol is required')
  }
  if (rawSymbol.length > MAX_SYMBOL_LENGTH) {
    throw clientError('EXPLAIN_INVALID_ARGUMENT', 'The function symbol is too long')
  }
  const payload = {
    symbol: rawSymbol,
    language: normalizeLanguage(input && input.language),
  }
  const rawQuestion = input && typeof input.question === 'string' ? input.question.trim() : ''
  if (rawQuestion.length > 0) {
    payload.question = rawQuestion.slice(0, MAX_QUESTION_LENGTH)
  }
  return payload
}

/**
 * Normalize a failure from the RPC layer into an Error with a stable `code`.
 * The message is bounded; server stacks are never copied into the payload.
 *
 * @param {unknown} error
 * @returns {Error & {code: string}}
 */
export function normalizeExplainError(error) {
  if (error && typeof error === 'object') {
    if (isAbortError(error)) return clientError('EXPLAIN_ABORTED', 'The explanation request was cancelled')
    const nested = error.error && typeof error.error === 'object' ? error.error : null
    const code =
      typeof error.code === 'string'
        ? error.code
        : nested && typeof nested.code === 'string'
          ? nested.code
          : 'EXPLAIN_CLIENT_ERROR'
    const rawMessage =
      typeof error.message === 'string' && error.message.length > 0
        ? error.message
        : nested && typeof nested.message === 'string'
          ? nested.message
          : 'Explanation request failed'
    const message =
      rawMessage.length > MAX_ERROR_MESSAGE ? `${rawMessage.slice(0, MAX_ERROR_MESSAGE)}…` : rawMessage
    return clientError(code, message)
  }
  return clientError('EXPLAIN_CLIENT_ERROR', typeof error === 'string' ? error : 'Explanation request failed')
}

/**
 * Normalize a Host `explain` result into `{symbol,text,model,evidenceCount,usage}`.
 *
 * @param {unknown} value
 * @param {string} [fallbackSymbol]
 */
export function normalizeExplainResult(value, fallbackSymbol) {
  if (!value || typeof value !== 'object') {
    throw clientError('EXPLAIN_PROTOCOL_ERROR', 'The explain RPC returned an invalid payload')
  }
  const text = typeof value.text === 'string' ? value.text.trim() : ''
  if (text.length === 0) {
    throw clientError('EXPLAIN_EMPTY', 'The model returned an empty explanation')
  }
  const symbol =
    typeof value.symbol === 'string' && value.symbol.length > 0
      ? value.symbol
      : typeof fallbackSymbol === 'string'
        ? fallbackSymbol
        : ''
  let model = null
  if (value.model && typeof value.model === 'object') {
    const provider = typeof value.model.provider === 'string' ? value.model.provider : ''
    const name = typeof value.model.model === 'string' ? value.model.model : ''
    if (provider && name) model = { provider, model: name }
  }
  const count = Number(value.evidenceCount)
  const evidenceCount = Number.isFinite(count) && count > 0 ? Math.floor(count) : 0
  const usage = value.usage && typeof value.usage === 'object' ? value.usage : null
  return {
    symbol,
    text,
    model,
    evidenceCount,
    usage,
  }
}

/**
 * Call the authenticated RPC endpoint and unwrap the Host envelope.
 * Works both with an `api.rpc` that returns the raw `{ok,value|error}` envelope
 * and with one that already unwraps to `value`.
 *
 * @param {{rpc?: (endpoint: string, payload: unknown, signal?: AbortSignal) => Promise<unknown>}|null|undefined} api
 * @param {{symbol: string, language: 'en'|'zh', question?: string}} payload
 * @param {AbortSignal} [signal]
 */
export async function unwrapExplainRpc(api, payload, signal) {
  if (!api || typeof api.rpc !== 'function') {
    throw clientError(
      'EXPLAIN_UNAVAILABLE',
      'The CA plugin RPC channel is unavailable (the plugin Client half is not ready)',
    )
  }
  let raw
  try {
    raw = await api.rpc(RPC_ENDPOINT, payload, signal)
  } catch (error) {
    throw normalizeExplainError(error)
  }
  if (raw && typeof raw === 'object') {
    if (raw.ok === false) throw normalizeExplainError(raw.error || raw)
    if (raw.ok === true) {
      return normalizeExplainResult(raw.value, payload.symbol)
    }
  }
  return normalizeExplainResult(raw, payload.symbol)
}

/**
 * Create the AI explanation panel component.
 *
 * @param {typeof import('react')} React the host React instance
 * @param {{ui?: Record<string, Function>, api?: {rpc?: Function}, i18n?: {t?: Function, lang?: string, subscribe?: Function}}} [bag]
 * @returns {(props: {symbol?: string, language?: string, onNavigate?: Function, auto?: boolean}) => unknown}
 */
export function createExplainPanel(React, bag = {}) {
  if (!React || typeof React.createElement !== 'function') {
    throw new TypeError('createExplainPanel(React, bag) requires a React instance')
  }
  const h = React.createElement
  const ui = (bag && bag.ui) || {}
  const api = bag && bag.api ? bag.api : null
  const i18n = bag && bag.i18n ? bag.i18n : null
  const styles = createStyles()

  const UiButton = typeof ui.Button === 'function' ? ui.Button : null
  const UiSpinner = typeof ui.Spinner === 'function' ? ui.Spinner : null

  /** Button primitive: prefer the shared UI primitive, fall back to <button>. */
  function Button(props) {
    if (UiButton) {
      return h(UiButton, {
        onClick: props.onClick,
        disabled: Boolean(props.disabled),
        title: props.title,
        style: props.style,
      }, props.children)
    }
    return h(
      'button',
      {
        type: 'button',
        onClick: props.onClick,
        disabled: Boolean(props.disabled),
        title: props.title,
        style: {
          ...styles.button,
          ...(props.style || {}),
          ...(props.disabled ? styles.buttonDisabled : null),
        },
      },
      props.children,
    )
  }

  function Spinner() {
    if (UiSpinner) return h(UiSpinner, null)
    return h('span', { style: styles.spinner, 'aria-hidden': true })
  }

  /** Re-render when the shared i18n language changes. */
  function useLanguageTick() {
    const [, setTick] = React.useState(0)
    React.useEffect(() => {
      if (!i18n || typeof i18n.subscribe !== 'function') return undefined
      let active = true
      let unsubscribe
      try {
        unsubscribe = i18n.subscribe(() => {
          if (active) setTick((value) => value + 1)
        })
      } catch {
        unsubscribe = undefined
      }
      return () => {
        active = false
        if (typeof unsubscribe === 'function') {
          try {
            unsubscribe()
          } catch {
            // ignore: a disposed i18n store
          }
        }
      }
    }, [])
  }

  function translate(language, key, vars) {
    const languageKey = normalizeLanguage(language)
    const namespaced =
      typeof key === 'string' && key.indexOf('.') >= 0 ? key : `explain.${String(key)}`
    let text = null
    if (i18n && typeof i18n.t === 'function') {
      try {
        text = i18n.t(namespaced, vars)
      } catch {
        text = null
      }
    }
    if (typeof text !== 'string' || text.length === 0 || text === namespaced || text === key) {
      const table = FALLBACK_STRINGS[languageKey] || FALLBACK_STRINGS.en
      text = table[key] || FALLBACK_STRINGS.en[key] || key
    }
    if (vars && typeof text === 'string') {
      text = text.replace(/\{(\w+)\}/g, (match, name) => (vars[name] === undefined ? match : String(vars[name])))
    }
    return text
  }

  function renderInline(tokens, keyPrefix, language, onNavigate) {
    const rendered = []
    for (let index = 0; index < tokens.length; index += 1) {
      const token = tokens[index]
      const key = `${keyPrefix}-${index}`
      if (token.type === 'strong') {
        rendered.push(h('strong', { key }, renderInline(token.tokens, key, language, onNavigate)))
      } else if (token.type === 'code') {
        rendered.push(h('code', { key, style: styles.inlineCode }, token.text))
      } else if (token.type === 'evidence') {
        rendered.push(h('span', { key, style: styles.evidence }, `[${token.ref}]`))
      } else if (token.type === 'location') {
        if (typeof onNavigate === 'function') {
          rendered.push(
            h(
              'button',
              {
                key,
                type: 'button',
                style: styles.location,
                title: translate(language, 'locationHint', { location: token.text }),
                onClick: () => {
                  try {
                    onNavigate({ file: token.file, line: token.line })
                  } catch {
                    // navigation is a host callback; never break rendering for it
                  }
                },
              },
              token.text,
            ),
          )
        } else {
          rendered.push(h('code', { key, style: styles.inlineCode }, token.text))
        }
      } else {
        rendered.push(token.text)
      }
    }
    return rendered
  }

  function MarkdownView(props) {
    const parsed = React.useMemo(() => parseMarkdown(props.text), [props.text])
    const children = []
    for (let index = 0; index < parsed.blocks.length; index += 1) {
      const block = parsed.blocks[index]
      const key = `b-${index}`
      if (block.type === 'heading') {
        const tag = block.level <= 1 ? 'h4' : block.level === 2 ? 'h5' : 'h6'
        const style =
          block.level <= 1
            ? styles.heading1
            : block.level === 2
              ? styles.heading2
              : block.level === 3
                ? styles.heading3
                : styles.headingSmall
        children.push(h(tag, { key, style }, renderInline(parseInline(block.text), key, props.language, props.onNavigate)))
      } else if (block.type === 'list') {
        const items = block.items.map((item, itemIndex) =>
          h(
            'li',
            { key: `i-${itemIndex}` },
            renderInline(parseInline(item), `${key}-${itemIndex}`, props.language, props.onNavigate),
          ),
        )
        children.push(h(block.ordered ? 'ol' : 'ul', { key, style: styles.list }, items))
      } else if (block.type === 'code') {
        children.push(h('pre', { key, style: styles.codeBlock }, h('code', { style: styles.codeText }, block.text)))
      } else if (block.type === 'quote') {
        children.push(
          h(
            'blockquote',
            { key, style: styles.blockquote },
            renderInline(parseInline(block.text), key, props.language, props.onNavigate),
          ),
        )
      } else if (block.type === 'hr') {
        children.push(h('hr', { key, style: styles.hr }))
      } else {
        children.push(
          h(
            'p',
            { key, style: styles.paragraph },
            renderInline(parseInline(block.text), key, props.language, props.onNavigate),
          ),
        )
      }
    }
    return h(
      'div',
      { style: styles.markdown },
      children,
      parsed.truncated
        ? h('p', { style: styles.muted }, translate(props.language, 'truncated'))
        : null,
    )
  }

  function ExplainPanel(props) {
    const safeProps = props || {}
    const rawSymbol = typeof safeProps.symbol === 'string' ? safeProps.symbol.trim() : ''
    const symbol = rawSymbol.length > MAX_SYMBOL_LENGTH ? rawSymbol.slice(0, MAX_SYMBOL_LENGTH) : rawSymbol
    const language = normalizeLanguage(safeProps.language || (i18n && i18n.lang))
    useLanguageTick()
    const t = (key, vars) => translate(language, key, vars)

    const [state, setState] = React.useState({ busy: false, result: null, error: null })
    const [question, setQuestion] = React.useState('')
    const [copied, setCopied] = React.useState(false)
    const [copyFailed, setCopyFailed] = React.useState(false)
    const mountedRef = React.useRef(true)
    const abortRef = React.useRef(null)
    const runSeqRef = React.useRef(0)
    const copyTimerRef = React.useRef(null)
    const rootRef = React.useRef(null)
    const runRef = React.useRef(null)

    React.useEffect(() => {
      return () => {
        mountedRef.current = false
        if (abortRef.current) {
          try {
            abortRef.current.abort()
          } catch {
            // already aborted
          }
        }
        if (copyTimerRef.current) clearTimeout(copyTimerRef.current)
      }
    }, [])

    React.useEffect(() => {
      if (abortRef.current) {
        try {
          abortRef.current.abort()
        } catch {
          // already aborted
        }
        abortRef.current = null
      }
      runSeqRef.current += 1
      setState({ busy: false, result: null, error: null })
      setCopied(false)
      setCopyFailed(false)
    }, [symbol])

    React.useEffect(() => {
      if (safeProps.auto && symbol && runRef.current) runRef.current()
    }, [symbol, Boolean(safeProps.auto)])

    function fallbackCopy(text) {
      try {
        if (typeof document === 'undefined') return false
        const host = rootRef.current
        if (!host || typeof host.appendChild !== 'function') return false
        const area = document.createElement('textarea')
        area.value = text
        area.setAttribute('readonly', '')
        area.style.position = 'absolute'
        area.style.left = '-9999px'
        area.style.top = '0'
        area.setAttribute('aria-hidden', 'true')
        host.appendChild(area)
        let ok = false
        try {
          area.select()
          ok = Boolean(document.execCommand && document.execCommand('copy'))
        } catch {
          ok = false
        }
        host.removeChild(area)
        return ok
      } catch {
        return false
      }
    }

    async function copyResult() {
      const text = state.result && typeof state.result.text === 'string' ? state.result.text : ''
      if (text.length === 0) return
      let ok = false
      try {
        if (
          typeof navigator !== 'undefined' &&
          navigator.clipboard &&
          typeof navigator.clipboard.writeText === 'function'
        ) {
          await navigator.clipboard.writeText(text)
          ok = true
        }
      } catch {
        ok = false
      }
      if (!ok) ok = fallbackCopy(text)
      if (!mountedRef.current) return
      setCopied(ok)
      setCopyFailed(!ok)
      if (copyTimerRef.current) clearTimeout(copyTimerRef.current)
      copyTimerRef.current = setTimeout(() => {
        if (!mountedRef.current) return
        setCopied(false)
        setCopyFailed(false)
      }, COPY_FEEDBACK_MS)
    }

    function stop() {
      if (abortRef.current) {
        try {
          abortRef.current.abort()
        } catch {
          // already aborted
        }
      }
    }

    async function run() {
      if (!symbol) return
      if (typeof AbortController !== 'function') {
        setState((previous) => ({
          ...previous,
          error: clientError('EXPLAIN_UNAVAILABLE', 'This browser does not support abortable requests'),
        }))
        return
      }
      if (abortRef.current) {
        try {
          abortRef.current.abort()
        } catch {
          // already aborted
        }
      }
      runSeqRef.current += 1
      const seq = runSeqRef.current
      const controller = new AbortController()
      abortRef.current = controller
      setCopied(false)
      setCopyFailed(false)
      setState((previous) => ({ busy: true, result: previous.result, error: null }))
      try {
        const payload = buildExplainRequest({ symbol, language, question })
        const result = await unwrapExplainRpc(api, payload, controller.signal)
        if (!mountedRef.current || seq !== runSeqRef.current || controller.signal.aborted) return
        setState({ busy: false, result, error: null })
      } catch (error) {
        if (!mountedRef.current || seq !== runSeqRef.current) return
        if (controller.signal.aborted || isAbortError(error)) {
          setState((previous) => ({ ...previous, busy: false, error: null }))
          return
        }
        setState((previous) => ({ ...previous, busy: false, error: normalizeExplainError(error) }))
      } finally {
        if (abortRef.current === controller) abortRef.current = null
      }
    }
    runRef.current = run

    function renderErrorBlock(error) {
      const code = error && typeof error.code === 'string' ? error.code : 'EXPLAIN_CLIENT_ERROR'
      const message =
        error && typeof error.message === 'string' && error.message.length > 0
          ? error.message
          : tr('error')
      const hint = code === 'EXPLAIN_UNAVAILABLE' ? h('div', { style: styles.muted }, tr('unavailableHint')) : null
      return h(
        'div',
        { style: styles.errorBox, role: 'alert' },
        h('div', { style: styles.errorTitle }, `${tr('error')} · ${code}`),
        h('div', { style: styles.errorMessage }, message),
        hint,
        h('div', { style: styles.errorActions }, h(Button, { onClick: run }, tr('retry'))),
      )
    }

    function renderResultBlock(result) {
      const modelLabel =
        result.model && result.model.provider && result.model.model
          ? `${result.model.provider}/${result.model.model}`
          : tr('modelFallback')
      return h(
        'div',
        { style: styles.result },
        h(MarkdownView, { text: result.text, language, onNavigate: safeProps.onNavigate }),
        h(
          'div',
          { style: styles.footer },
          result.evidenceCount > 0
            ? h('span', { style: styles.meta }, tr('evidence', { count: result.evidenceCount }))
            : h('span', { style: styles.meta }),
          h(
            Button,
            { onClick: copyResult, style: styles.smallButton },
            copied ? tr('copied') : copyFailed ? tr('copyFailed') : tr('copy'),
          ),
        ),
        h('p', { style: styles.disclaimer }, tr('disclaimer', { model: modelLabel })),
      )
    }

    const busy = state.busy
    const result = state.result
    const error = state.error
    const tr = t

    return h(
      'section',
      {
        className: 'ca-explain',
        style: styles.root,
        'aria-label': tr('title'),
        ref: rootRef,
      },
      h(
        'div',
        { style: styles.header },
        h(
          'div',
          { style: styles.titleWrap },
          h('span', { style: styles.title }, tr('title')),
          result && result.model
            ? h('span', { style: styles.badge, title: `${result.model.provider}/${result.model.model}` }, `${result.model.provider}/${result.model.model}`)
            : null,
        ),
        h(
          'div',
          { style: styles.actions },
          busy
            ? h(Button, { onClick: stop, title: tr('stop') }, tr('stop'))
            : h(
                Button,
                {
                  onClick: run,
                  disabled: symbol.length === 0,
                  title: result ? tr('regenerate') : tr('explain'),
                },
                result ? tr('regenerate') : tr('explain'),
              ),
        ),
      ),
      h(
        'div',
        { style: styles.questionRow },
        h('input', {
          type: 'text',
          style: styles.input,
          value: question,
          maxLength: MAX_QUESTION_LENGTH,
          placeholder: tr('questionPlaceholder'),
          'aria-label': tr('questionLabel'),
          onChange: (event) => setQuestion(event.target.value),
          onKeyDown: (event) => {
            if (event.key === 'Enter' && !busy) {
              event.preventDefault()
              run()
            }
          },
        }),
      ),
      symbol.length === 0 ? h('p', { style: styles.muted }, tr('invalidSymbol')) : null,
      error ? renderErrorBlock(error) : null,
      busy
        ? h(
            'div',
            { style: styles.loading, role: 'status', 'aria-live': 'polite' },
            h(Spinner, null),
            h('span', null, tr('loading')),
          )
        : result
          ? renderResultBlock(result)
          : null,
    )
  }

  ExplainPanel.displayName = 'CaExplainPanel'
  return ExplainPanel
}

